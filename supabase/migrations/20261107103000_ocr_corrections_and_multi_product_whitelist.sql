-- OCR correction training records and multi-product company whitelist.
create table if not exists public.ocr_corrections (
  id bigint generated by default as identity primary key,
  raw_text text not null default '',
  original_json jsonb not null default '[]'::jsonb,
  corrected_json jsonb not null default '[]'::jsonb,
  source_file text not null default '',
  ocr_pipeline text not null default 'ai_vision',
  ocr_mode text not null default 'bulk',
  edit_count integer not null default 0,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.ocr_corrections enable row level security;
revoke all on table public.ocr_corrections from anon, authenticated;
grant all on table public.ocr_corrections to service_role;
grant usage, select on sequence public.ocr_corrections_id_seq to service_role;

-- Preserve all existing rows while allowing the same company to have multiple products.
create unique index if not exists whitelist_companies_company_product_uidx
  on public.whitelist_companies (company_name, bank_name);

alter table public.whitelist_companies
  drop constraint if exists whitelist_companies_company_name_key;
